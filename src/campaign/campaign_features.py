def extract_campaign_features_batch(
    df: pd.DataFrame,
    url_column: str = "url",
) -> pd.DataFrame:
    """
    Extract campaign features for an entire dataframe.

    Unlike the single URL API, this batch API computes
    additional batch-context features describing
    infrastructure reuse across the analysed URLs.
    """

    if url_column not in df.columns:
        raise ValueError(
            f"Column '{url_column}' not found in dataframe."
        )

    feature_rows = []

    for url in df[url_column]:

        #
        # --------------------------------------------------------
        # Frozen prediction features
        # --------------------------------------------------------
        #
        # IMPORTANT:
        # Preserve the existing campaign feature engineering.
        # Only the underlying feature acquisition is updated to
        # use the current Infrastructure Package.
        #

        url_features = extract_url_features(url)

        # Preserve the exact HTML behaviour used during
        # XGBoost infrastructure training.
        html_features = {
            "num_forms": 0,
            "num_iframes": 0,
            "num_scripts": 0,
            "num_links": 0,
            "has_event_handlers": 0
        }

        domain = extract_domain_in_features_with_infra(url)

        infra_result = collect_infrastructure_features(
            domain,
            FEATURE_SECTION_DATA
        )

        infra_features = infra_result["features"]

        prediction_features = {}

        prediction_features.update(url_features)
        prediction_features.update(html_features)
        prediction_features.update(infra_features)

        prediction_features = select_prediction_features(
            prediction_features
        )
        
        #
        # --------------------------------------------------------
        # Campaign metadata
        # --------------------------------------------------------
        #
        domain = extract_domain_in_features_with_infra(url)

        metadata = get_campaign_metadata(domain)

        metadata_features = encode_campaign_metadata(
            metadata
        )

        #
        # --------------------------------------------------------
        # Merge feature vector
        # --------------------------------------------------------
        #
        feature_vector = {}

        feature_vector.update(
            prediction_features
        )

        feature_vector.update(
            metadata_features
        )

        #
        # --------------------------------------------------------
        # Temporary metadata
        #
        # These fields are required only for computing
        # batch-context reuse features.
        #
        # They will be removed later.
        # --------------------------------------------------------
        #
        feature_vector["organization"] = metadata.get(
            "organization") or "UNKNOWN"

        feature_vector["hosting_provider"] = metadata.get(
            "hosting_provider") or "UNKNOWN"

        #
        # campaign_metadata.py stores the ASN information
        # in the "as" field.
        #
        feature_vector["as"] = metadata.get(
            "as") or "UNKNOWN"


        feature_rows.append(
            feature_vector
        )

    #
    # --------------------------------------------------------
    # Build dataframe
    # --------------------------------------------------------
    #
    feature_df = pd.DataFrame(
        feature_rows
    )

    print(
        feature_df[
            [
                "organization",
                "hosting_provider",
                "as",
            ]
        ].head(15)
    )

    print("\nOrganization values")
    print(feature_df["organization"].value_counts())

    print("\nHosting Provider values")
    print(feature_df["hosting_provider"].value_counts())

    print("\nAS values")
    print(feature_df["as"].value_counts())

    #
    # --------------------------------------------------------
    # Compute batch-context reuse features.
    #
    # This function also removes the temporary
    # metadata columns.
    # --------------------------------------------------------
    #
    feature_df = compute_batch_context_features(
        feature_df
    )

    #
    # --------------------------------------------------------
    # TEMPORARY DEBUG
    # Verify reuse feature values
    # Remove after validation.
    # --------------------------------------------------------
    #
    print("\nBatch Context Features")
    print(feature_df[
        [
            "organization_reuse",
            "hosting_provider_reuse",
            "asn_reuse",
        ]
    ].describe())

    print(
        feature_df[
            [
                "organization_reuse",
                "hosting_provider_reuse",
                "asn_reuse",
            ]
        ].head(10)
    )


    #
    # --------------------------------------------------------
    # Ensure deterministic column ordering.
    #
    # DBSCAN depends on this ordering.
    # --------------------------------------------------------
    #
    feature_df = feature_df[
        CAMPAIGN_FEATURES
    ]

    #
    # --------------------------------------------------------
    # Optional feature cache for debugging / research.
    # This stores the final engineered feature matrix
    # before clustering.
    # --------------------------------------------------------
    #
    if SAVE_CAMPAIGN_FEATURE_CACHE:

        os.makedirs(
            os.path.dirname(CAMPAIGN_FEATURE_CACHE_PATH),
            exist_ok=True,
        )

        feature_df.to_csv(
            CAMPAIGN_FEATURE_CACHE_PATH,
            index=False,
        )    


    return feature_df

