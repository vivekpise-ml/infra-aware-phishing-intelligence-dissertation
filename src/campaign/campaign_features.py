def extract_campaign_features(
    url: str,
) -> Dict:
    """
    Extract campaign-oriented features for a single URL.

    Pipeline
    --------
        URL
          │
          ├── Frozen prediction features
          │
          └── Campaign metadata
                     │
                     ▼
              Numeric encoding
                     │
                     ▼
            Campaign feature vector

    Parameters
    ----------
    url : str

    Returns
    -------
    Dict
        Numerical feature vector suitable for DBSCAN.
    """

    #
    # -----------------------------
    # Frozen prediction features
    # -----------------------------
    #
    # IMPORTANT:
    # The campaign feature definitions remain unchanged.
    # Only the feature acquisition path is aligned with
    # the current Infrastructure Package.
    #

    url_features = extract_url_features(url)

    # Preserve the exact HTML behaviour used during
    # XGBoost infrastructure training.
    # Campaign analysis currently has no HTML input.
    html_features = {
        "num_forms": 0,
        "num_iframes": 0,
        "num_scripts": 0,
        "num_links": 0,
        "has_event_handlers": 0
    }

    domain = extract_domain_in_features_with_infra(url)

    infra_result = collect_infrastructure_features(
        domain,
        FEATURE_SECTION_DATA
    )

    infra_features = infra_result["features"]

    prediction_features = {}

    prediction_features.update(url_features)
    prediction_features.update(html_features)
    prediction_features.update(infra_features)

    prediction_features = select_prediction_features(
        prediction_features
    )

    #
    # -----------------------------
    # Campaign metadata
    # -----------------------------
    #
    domain = extract_domain_in_features_with_infra(url)

    metadata = get_campaign_metadata(domain)

    metadata_features = encode_campaign_metadata(
        metadata
    )

    #
    # -----------------------------
    # Merge
    # -----------------------------
    #
    feature_vector = {}

    #
    # Prediction-derived features
    #
    feature_vector.update(
        prediction_features
    )

    #
    # Campaign metadata features
    #
    feature_vector.update(
        metadata_features
    )

    #
    # -----------------------------
    # Safety check
    # -----------------------------
    #
    # Ensure every expected feature exists.
    #
    for feature in CAMPAIGN_FEATURES:

        if feature not in feature_vector:

            feature_vector[feature] = 0

    return feature_vector


# ============================================================
# Internal Validation
# ============================================================

def validate_feature_vector(
    feature_vector: Dict,
) -> Dict:
    """
    Validate the campaign feature vector.

    This function ensures:

    1. Every required feature exists.
    2. Missing values become zero.
    3. None values become zero.
    """

    validated = {}

    for feature in CAMPAIGN_FEATURES:

        value = feature_vector.get(
            feature,
            0,
        )

        if value is None:
            value = 0

        validated[feature] = value

    return validated


# ============================================================
# Single URL API
# ============================================================

def get_campaign_feature_vector(
    url: str,
) -> Dict:
    """
    Public helper used by the campaign module.

    This wrapper keeps future preprocessing changes
    isolated from callers.
    """

    feature_vector = extract_campaign_features(
        url
    )

    feature_vector = validate_feature_vector(
        feature_vector
    )

    return feature_vector

