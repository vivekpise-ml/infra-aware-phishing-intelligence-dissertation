def compute_batch_context_features(
    feature_df: pd.DataFrame,
) -> pd.DataFrame:
    """
    Compute batch-level campaign context features.

    These features are derived from metadata shared across the
    analysed URL batch rather than from individual URLs.

    Temporary metadata columns expected:

        organization
        hosting_provider
        as

    Generated features:

        organization_reuse
        hosting_provider_reuse
        asn_reuse

    The temporary metadata columns are removed before returning
    the final dataframe.
    """

    #
    # Empty dataframe
    #
    if feature_df.empty:
        return feature_df

    #
    # -----------------------------------------
    # Organization reuse
    # -----------------------------------------
    #
    organization_counts = (
        feature_df["organization"]
        .fillna("UNKNOWN")
        .replace("", "UNKNOWN")
        .value_counts()
    )

    feature_df["organization_reuse"] = (
        feature_df["organization"]
        .fillna("UNKNOWN")
        .replace("", "UNKNOWN")
        .map(organization_counts)
        .astype(int)
    )

    #
    # -----------------------------------------
    # Hosting provider reuse
    # -----------------------------------------
    #
    provider_counts = (
        feature_df["hosting_provider"]
        .fillna("UNKNOWN")
        .replace("", "UNKNOWN")
        .value_counts()
    )

    feature_df["hosting_provider_reuse"] = (
        feature_df["hosting_provider"]
        .fillna("UNKNOWN")
        .replace("", "UNKNOWN")
        .map(provider_counts)
        .astype(int)
    )

    #
    # -----------------------------------------
    # ASN reuse
    #
    # campaign_metadata.py exposes the raw
    # Autonomous System string as "as".
    # The resulting feature is named "asn_reuse"
    # for consistency with the research paper.
    # -----------------------------------------
    #
    as_counts = (
        feature_df["as"]
        .fillna("UNKNOWN")
        .replace("", "UNKNOWN")
        .value_counts()
    )

    feature_df["asn_reuse"] = (
        feature_df["as"]
        .fillna("UNKNOWN")
        .replace("", "UNKNOWN")
        .map(as_counts)
        .astype(int)
    )

    '''
    #
    # Remove temporary metadata columns.
    #
    feature_df.drop(
        columns=[
            "organization",
            "hosting_provider",
            "as",
        ],
        inplace=True,
        errors="ignore",
    )
    '''

    return feature_df

