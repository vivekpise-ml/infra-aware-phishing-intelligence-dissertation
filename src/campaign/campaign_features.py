def stable_hash(value: str, modulo: int = 100003) -> int:
    """
    Convert arbitrary text into a stable integer.

    Python's built-in hash() is intentionally randomised
    between interpreter sessions.

    SHA256 provides deterministic values.
    """

    if value is None:
        return 0

    value = str(value).strip()

    if value == "":
        return 0

    digest = hashlib.sha256(
        value.encode("utf-8")
    ).hexdigest()

    return int(digest[:12], 16) % modulo


def encode_campaign_metadata(
    metadata: Dict,
) -> Dict:
    """
    Convert campaign metadata into numerical features
    suitable for clustering.
    """

    return {

        "ssl_available":

            metadata.get(
                "ssl_available",
                0,
            ),

        "ssl_validity_bucket":

            metadata.get(
                "ssl_validity_bucket",
                0,
            ),

        "ssl_days_remaining":

            max(
                metadata.get(
                    "ssl_days_remaining",
                    0,
                ),
                0,
            ),

        "nameserver_count":

            metadata.get(
                "nameserver_count",
                0,
            ),

        #
        # -----------------------------
        # Derived operational metadata
        # -----------------------------
        #

        "has_multiple_nameservers":

            int(
                metadata.get(
                    "nameserver_count",
                    0,
                ) >= 2
            ),

        "high_nameserver_diversity":

            int(
                metadata.get(
                    "nameserver_count",
                    0,
                ) >= 4
            ),

        "ssl_near_expiry":

            int(
                0
                <
                metadata.get(
                    "ssl_days_remaining",
                    0,
                )
                <=
                30
            ),

        "long_lived_certificate":

            int(
                metadata.get(
                    "ssl_days_remaining",
                    0,
                )
                >=
                365
            ),
        
    }


def select_prediction_features(
    feature_dict: Dict,
) -> Dict:
    """
    Select only the prediction features required for
    campaign analysis.

    Missing values are replaced with zero.
    """

    selected = {}

    for feature in (

        LEXICAL_FEATURES

        +

        INFRASTRUCTURE_FEATURES

    ):

        selected[feature] = feature_dict.get(
            feature,
            0,
        )

    return selected

